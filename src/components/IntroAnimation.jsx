export default function IntroAnimation() {
  const [show, setShow] = useState(true);
  const overlay = useRef(null);
  const svg = useRef(null);

  useEffect(() => {
    // Lock scrolling while the intro plays
    const prevOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    const ctx = gsap.context(() => {
      const paths = svg.current.querySelectorAll("path");
      const tl = gsap.timeline({ delay: 0.3, defaults: { ease: "power2.inOut" } });

      paths.forEach((p, i) =>
        tl.to(p, { morphSVG: DESIGNER[i], duration: 0.8 }, i * 0.08)
      );
      paths.forEach((p, i) =>
        tl.to(p, { morphSVG: DEVELOPER[i], duration: 0.8 }, 2.2 + i * 0.08)
      );
      tl.to(overlay.current, {
        opacity: 0,
        duration: 0.6,
        delay: 1,
        onComplete: () => {
          document.body.style.overflow = prevOverflow;
          setShow(false);
        },
      });
    }, overlay);

    return () => {
      ctx.revert();
      document.body.style.overflow = prevOverflow;
    };
  }, []);

  if (!show) return null;

  return (
    <div
      ref={overlay}
      aria-hidden="true"
      style={{
        position: "fixed",
        inset: 0,
        zIndex: 9999,
        background: "#000000",
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
      }}
    >
      <svg ref={svg} viewBox="0 0 1300 400" style={{ width: "100%", maxWidth: 1300 }}>
        <defs>
          <linearGradient id="intro-grad" x1="0" y1="1" x2="1" y2="0">
            <stop offset="0.1" stopColor="#212323" />
            <stop offset="0.7" stopColor="#12a77aca" />
          </linearGradient>
        </defs>
        {SHAPES.map((d, i) => (
          <path key={i} d={d} fill="url(#intro-grad)" />
        ))}
      </svg>
    </div>
  );
}